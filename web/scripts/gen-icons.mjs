#!/usr/bin/env node
// Writes src/lib/icons.ts: the path data of the Phosphor icons the client uses (the same icon
// set as the desktop app). Add a name to NAMES and run `node scripts/gen-icons.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const NAMES = `
house film-strip television-simple music-notes music-note book-open video-camera image folder folder-open
folder-plus download-simple magnifying-glass rss gear-six sign-out user users devices shield-check list x check
plus minus trash pause play play-fill pause-fill skip-forward-fill skip-back-fill shuffle repeat speaker-high
speaker-low speaker-x corners-out corners-in picture-in-picture gauge heart heart-fill check-circle
check-circle-fill circle caret-left caret-right caret-down caret-up arrow-left arrow-clockwise
arrow-counter-clockwise arrow-up arrow-down funnel sort-ascending sort-descending dots-three-vertical dots-three
pencil-simple magnet upload-simple link tag hard-drives warning warning-circle info lock key copy eye eye-slash
palette sliders-horizontal clock hourglass-medium arrow-circle-down arrow-circle-up pause-circle circle-notch queue
rows squares-four scroll terminal-window sun moon desktop translate sparkle clock-counter-clockwise list-numbers
closed-captioning x-circle globe user-plus qr-code playlist dots-six-vertical rewind fast-forward speedometer
microphone-stage books stop arrow-line-up arrow-line-down arrows-clockwise broadcast check-square square
minus-square file arrow-square-out cloud-arrow-down puzzle-piece bookmark-simple trash-simple user-circle circles-three plus-circle stack bell archive play-circle screencast
lightning folder-simple-dashed folder-simple scales flag minus-circle globe-simple arrow-right film-slate
`.trim().split(/\s+/);

const base = resolve(import.meta.dirname, '../node_modules/@phosphor-icons/core/assets');
const out = {};
for (const n of NAMES) {
  const fill = n.endsWith('-fill');
  const file = resolve(base, fill ? 'fill' : 'regular', `${n}.svg`);
  const svg = readFileSync(file, 'utf8');
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  out[n] = inner;
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  resolve(import.meta.dirname, '../src/lib/icons.ts'),
  `// Generated by scripts/gen-icons.mjs from @phosphor-icons/core (MIT). Do not edit.\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`${NAMES.length} icons`);
